#!/usr/bin/env python3
"""Writes beads/templates.goose from the files bd init writes, as upstream
ships them (docs/spec/upstream/v1.3.0/init-templates/). Run it after
updating those files: python3 scripts/gen-templates.py"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "spec", "upstream", "v1.3.0", "init-templates")
FILES = [
    ("README", "README.md", "The .beads/README.md bd init writes."),
    ("BEADS_GITIGNORE", "beads.gitignore", "The .beads/.gitignore bd init writes."),
    ("CONFIG_YAML", "config.yaml", "The .beads/config.yaml bd init writes."),
    ("ROOT_GITIGNORE", "root.gitignore.fragment", "What bd init adds to the project's .gitignore."),
]


def literal(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    lines = [
        "// The files bd init writes, as beads v1.3.0 writes them. Generated by",
        "// scripts/gen-templates.py from docs/spec/upstream/v1.3.0/init-templates/;",
        "// edit those and regenerate.",
        "",
        "namespace templates;",
    ]
    for name, path, doc in FILES:
        with open(os.path.join(SRC, path), encoding="utf-8") as f:
            text = f.read()
        lines += ["", "// " + doc, "let " + name + " = " + literal(text) + ";"]
    with open(os.path.join(ROOT, "beads", "templates.goose"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


main()
